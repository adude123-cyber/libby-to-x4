#!/bin/sh
# Rebuilds plugin/plugin.js (the on-reader version) from wizard.js.
# Non-ASCII is escaped as \uXXXX since the reader may not send a charset.
set -e
cd "$(dirname "$0")"
{
  echo "// generated by build.sh from wizard.js. edit wizard.js, not this file."
  cat wizard.js
  cat <<'JS'
CrossPoint.registerPlugin(function (container) {
  // The headless /plugins-run page loads every plugin; there's nothing to show there.
  if (location.pathname.indexOf('/plugins-run') === 0) return;
  window.LibbyX4.mount(container, { mode: 'device' });
});
JS
} | perl -CSD -pe 's/([^\x00-\x7f])/sprintf("\\u%04x", ord($1))/ge' > plugin/plugin.js
echo "built plugin/plugin.js ($(wc -c < plugin/plugin.js) bytes)"
